def by_id(mock_id):
    """按 id 取一条模拟点记录，取不到返回 None。"""
    for m in MOCKS:
        if m["id"] == mock_id:
            return m
    return None


def level_label(level):
    return LEVELS.get(level, {}).get("label", level)


def level_desc(level):
    return LEVELS.get(level, {}).get("desc", "")


def grouped_by_level():
    """按级别分组，返回 [(级别, [记录...]), ...]，顺序为 critical → high → low。"""
    order = ["critical", "high", "low"]
    out = []
    for lv in order:
        items = [m for m in MOCKS if m["level"] == lv]
        if items:
            out.append((lv, items))
    return out


def total():
    return len(MOCKS)
